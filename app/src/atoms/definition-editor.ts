// Mapping with joined target column info for the review UI
export type MappingWithDetails = Tables<"import_mapping"> & {
  import_source_column: Pick<Tables<"import_source_column">, "column_name" | "priority"> | null;
  import_data_column: Pick<Tables<"import_data_column">, "column_name" | "purpose" | "column_type"> | null;
};

// Helper: call PostgREST RPC via fetchWithAuthRefresh (for functions not in generated types)
async function callRpc(
  fnName: string,
  params: Record<string, unknown>,
): Promise<void> {
  const res = await fetchWithAuthRefresh(`/rest/rpc/${fnName}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(params),
  });
  if (!res.ok) {
    const body = await res.json().catch(() => ({ message: res.statusText }));
    throw new Error(body.message || `RPC ${fnName} failed: ${res.status}`);
  }
}

// Create a new definition, link steps, and create source column mappings
export const createDefinitionAtom = atom(
  null,
  async (
    get,
    _set,
    params: {
      name: string;
      mode: Enums<"import_mode">;
      strategy: Enums<"import_strategy">;
      valid_time_from: Enums<"import_valid_time_from">;
      note: string | null;
      sourceColumns: string[];
    },
  ): Promise<Tables<"import_definition">> => {
    const client = get(restClientAtom);
    if (!client) throw new Error("Client not initialized");

    let def: Tables<"import_definition"> | null = null;
    try {
      // 1. Insert definition (slug auto-generated by trigger)
      const { data: inserted, error: defErr } = await client
        .from("import_definition")
        .insert({
          name: params.name,
          slug: "", // trigger will auto-generate
          mode: params.mode,
          strategy: params.strategy,
          valid_time_from: params.valid_time_from,
          note: params.note,
          custom: true,
        })
        .select("*")
        .single();
      if (defErr) throw defErr;
      if (!inserted) throw new Error("No definition returned");
      def = inserted;

      // 2. Link steps based on mode
      const stepCodes = getStepCodesForMode(params.mode);
      await callRpc("import_definition_link_steps", {
        p_definition_id: def.id,
        p_step_codes: stepCodes,
      });

      // 3. Create source columns and auto-match mappings
      if (params.sourceColumns.length > 0) {
        await callRpc("import_definition_create_source_and_mappings", {
          p_definition_id: def.id,
          p_source_columns: params.sourceColumns,
        });
      }

      // 4. Re-fetch the definition (validation trigger may have updated valid/validation_error)
      const { data: refreshed, error: refreshErr } = await client
        .from("import_definition")
        .select("*")
        .eq("id", def.id)
        .single();
      if (refreshErr) throw refreshErr;

      return refreshed ?? def;
    } catch (err) {
      // Clean up orphan definition if it was created but subsequent steps failed
      if (def) {
        await client.from("import_definition").delete().eq("id", def.id);
      }
      throw err;
    }
  },
);

// Fetch mappings with details for a definition
export const fetchDefinitionMappingsAtom = atom(
  null,
  async (
    get,
    _set,
    definitionId: number,
  ): Promise<MappingWithDetails[]> => {
    const client = get(restClientAtom);
    if (!client) throw new Error("Client not initialized");

    // Use PostgREST hint to disambiguate import_data_column relationship
    const { data, error } = await client
      .from("import_mapping")
      .select(
        "*, import_source_column!source_column_id(column_name, priority), import_data_column!target_data_column_id(column_name, purpose, column_type)",
      )
      .eq("definition_id", definitionId)
      .order("id");
    if (error) throw error;
    return (data ?? []) as MappingWithDetails[];
  },
);

// Fetch available target data columns for a definition's linked steps
export const fetchAvailableTargetColumnsAtom = atom(
  null,
  async (
    get,
    _set,
    definitionId: number,
  ): Promise<Tables<"import_data_column">[]> => {
    const client = get(restClientAtom);
    if (!client) throw new Error("Client not initialized");

    // Get step IDs linked to this definition
    const { data: defSteps, error: dsErr } = await client
      .from("import_definition_step")
      .select("step_id")
      .eq("definition_id", definitionId);
    if (dsErr) throw dsErr;
    if (!defSteps || defSteps.length === 0) return [];

    const stepIds = defSteps.map((ds) => ds.step_id);

    const { data, error } = await client
      .from("import_data_column")
      .select("*")
      .in("step_id", stepIds)
      .eq("purpose", "source_input")
      .order("step_id")
      .order("priority");
    if (error) throw error;
    return data ?? [];
  },
);

// Update a single mapping (change target column or toggle ignored)
export const updateMappingAtom = atom(
  null,
  async (
    get,
    _set,
    params: {
      mappingId: number;
      targetDataColumnId: number | null;
      isIgnored: boolean;
    },
  ): Promise<void> => {
    const client = get(restClientAtom);
    if (!client) throw new Error("Client not initialized");

    if (params.isIgnored) {
      const { error } = await client
        .from("import_mapping")
        .update({
          target_data_column_id: null,
          target_data_column_purpose: null,
          is_ignored: true,
        })
        .eq("id", params.mappingId);
      if (error) throw error;
    } else {
      const { error } = await client
        .from("import_mapping")
        .update({
          target_data_column_id: params.targetDataColumnId,
          target_data_column_purpose: "source_input",
          is_ignored: false,
        })
        .eq("id", params.mappingId);
      if (error) throw error;
    }
  },
);

